export function locale(): 'zh-CN' | 'en' {
  const language = typeof document === 'undefined' ? '' : document.documentElement?.lang;
  return !language || language.startsWith('zh') ? 'zh-CN' : 'en';
}

export type QqLocaleKey = keyof typeof english;

export function t(key: QqLocaleKey, ...params: readonly unknown[]): string {
  return (locale() === 'en' ? english[key] : key).replace(/\{(\d+)\}/g, (_, position) => String(params[Number(position)] ?? ''));
}

function subscribe(listener: () => void): () => void {
  if (typeof document === 'undefined' || typeof MutationObserver === 'undefined') return () => {};
  const observer = new MutationObserver(listener);
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] });
  return () => observer.disconnect();
}

export function useQqLocale(): ReturnType<typeof locale> {
  return useSyncExternalStore(subscribe, locale);
}
